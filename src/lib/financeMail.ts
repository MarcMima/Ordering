// Resend wrapper for finance mails (supports cc + reply-to; meetingEmails' sender does not).
import { renderEmail } from "@/lib/meetingEmails";
import type { Statement } from "@/lib/loanStatement";

export const FINANCE_OWNER = "marc@mimafood.nl";

export async function sendFinanceMail(m: {
  to: string[];
  cc?: string[];
  subject: string;
  html: string;
  text: string;
  replyTo?: string;
}): Promise<{ ok: boolean; error?: string }> {
  const key = process.env.RESEND_API_KEY;
  if (!key) return { ok: false, error: "RESEND_API_KEY missing" };
  const from = process.env.LOAN_STATEMENT_FROM ?? process.env.FROM_EMAIL ?? "bestelling@mimafood.nl";
  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${key}` },
      body: JSON.stringify({
        from,
        to: m.to,
        cc: m.cc?.length ? m.cc : undefined,
        reply_to: m.replyTo ?? FINANCE_OWNER,
        subject: m.subject,
        text: m.text,
        html: m.html,
      }),
    });
    if (!res.ok) return { ok: false, error: `${res.status} ${await res.text().catch(() => "")}` };
    return { ok: true };
  } catch (e) {
    return { ok: false, error: e instanceof Error ? e.message : String(e) };
  }
}

/** Preview mail to Marc: a short note on top, the statement exactly as the lender would get it below. */
export function previewMail(st: Statement, appUrl: string, lenderEmail: string | null) {
  const checks = [
    ...st.warnings,
    ...(lenderEmail ? [] : ["No lender email set yet. Add it on the Loans page before sending."]),
  ];
  const note = renderEmail({
    eyebrow: "Loans &middot; lender statement",
    heading: "The quarterly statement is ready to review",
    paragraphs: [
      `The statement for <strong>${st.periodStart}</strong> to <strong>${st.periodEnd}</strong> is below, exactly as the lender will receive it. Nothing has been sent to her yet.`,
      checks.length
        ? `Check first:<br>${checks.map((c) => `&middot; ${c}`).join("<br>")}`
        : "All instalments are recorded and on schedule.",
      "Open the Loans page to send it (you are copied in).",
    ],
    buttonLabel: "Review and send",
    buttonUrl: `${appUrl}/admin/finance/loans`,
    footer: "Only you receive this. It is generated by the Ordering app on the 2nd day of each quarter.",
  });
  const text =
    `The lender statement for ${st.periodStart} to ${st.periodEnd} is ready. Nothing has been sent yet.\n` +
    (checks.length ? `\nCheck first:\n${checks.map((c) => `- ${c}`).join("\n")}\n` : "") +
    `\nReview and send: ${appUrl}/admin/finance/loans\n\n--------\n\n${st.text}`;
  return { subject: `Review: ${st.subject}`, html: note + st.html, text };
}
